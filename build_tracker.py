GAP_FIELDS = ["error_class", "reported_total", "actual_total", "gap"]
INTERACTION_LABEL = "interaction"


def true_fee_billed_total(clean: pd.DataFrame) -> float:
    """Sum FeeBilled on the clean control (all base data rows)."""
    return float(clean["FeeBilled"].astype(float).sum())


def naive_sum_fee_billed(path: Path) -> float:
    """Excel-style =SUM(J2:J2001): numeric cells only in the fixed range."""
    wb = load_workbook(path, data_only=True)
    ws = wb[SHEET_NAME]
    total = 0.0
    for row in range(NAIVE_SUM_FIRST_ROW, NAIVE_SUM_LAST_ROW + 1):
        val = ws[f"J{row}"].value
        if isinstance(val, bool):
            continue
        if isinstance(val, (int, float)):
            total += float(val)
    wb.close()
    return total


def rows_outside_naive_range(path: Path) -> int:
    wb = load_workbook(path, data_only=True)
    ws = wb[SHEET_NAME]
    last_data_row = ws.max_row
    wb.close()
    if last_data_row <= NAIVE_SUM_LAST_ROW:
        return 0
    return last_data_row - NAIVE_SUM_LAST_ROW


