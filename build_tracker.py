def apply_injections(
    clean: pd.DataFrame,
    rng: random.Random,
    only_class: str | None = None,
) -> tuple[pd.DataFrame, list[InjectionLogRow], dict[str, Any]]:
    broken = clean.copy(deep=True)
    log: list[InjectionLogRow] = []
    used: set[int] = set()

    # --- Numbers stored as text (4 FeeBilled, 2 PolicyAmount) — logged now, applied in openpyxl ---
    fee_rows = _pick_indices(rng, 4, used)
    used.update(fee_rows)
    policy_rows = _pick_indices(rng, 2, used)
    used.update(policy_rows)
    text_targets: list[tuple[int, str, str]] = []
    for idx in fee_rows:
        text_targets.append((idx, "FeeBilled", "numbers_stored_as_text"))
    for idx in policy_rows:
        text_targets.append((idx, "PolicyAmount", "numbers_stored_as_text"))
    if _injecting(only_class, "numbers_stored_as_text"):
        for idx, col, key in text_targets:
            orig = broken.at[idx, col]
            log.append(
                InjectionLogRow(
                    row=_excel_row(idx),
                    column=col,
                    class_name=CLASS_LABELS[key],
                    original_value=_fmt_cell(orig),
                    corrupted_value=_fmt_cell(orig),
                )
            )
    elif only_class is not None:
        text_targets = []

    # --- Leading / trailing whitespace ---
    ws_client = _pick_indices(rng, 3, used)
    used.update(ws_client)
    ws_status = _pick_indices(rng, 2, used)
    used.update(ws_status)
    if _injecting(only_class, "leading_trailing_whitespace"):
        for idx in ws_client:
            orig = broken.at[idx, "ClientName"]
            broken.at[idx, "ClientName"] = f" {orig} "
            log.append(
                InjectionLogRow(
                    row=_excel_row(idx),
                    column="ClientName",
                    class_name=CLASS_LABELS["leading_trailing_whitespace"],
                    original_value=_fmt_cell(orig),
                    corrupted_value=broken.at[idx, "ClientName"],
                )
            )
        for idx in ws_status:
            orig = broken.at[idx, "Status"]
            broken.at[idx, "Status"] = f"{orig} "
            log.append(
                InjectionLogRow(
                    row=_excel_row(idx),
                    column="Status",
                    class_name=CLASS_LABELS["leading_trailing_whitespace"],
                    original_value=_fmt_cell(orig),
                    corrupted_value=broken.at[idx, "Status"],
                )
            )

    # --- Mixed US and ISO dates ---
    od_rows = _pick_indices(rng, 3, used)
    used.update(od_rows)
    lc_rows = _pick_indices(rng, 2, used)
    used.update(lc_rows)
    if _injecting(only_class, "mixed_us_iso_dates"):
        for idx in od_rows:
            orig = broken.at[idx, "OpenDate"]
            broken.at[idx, "OpenDate"] = _us_date_from_iso(str(orig))
            log.append(
                InjectionLogRow(
                    row=_excel_row(idx),
                    column="OpenDate",
                    class_name=CLASS_LABELS["mixed_us_iso_dates"],
                    original_value=_fmt_cell(orig),
                    corrupted_value=broken.at[idx, "OpenDate"],
                )
            )
        for idx in lc_rows:
            orig = broken.at[idx, "LastContactDate"]
            broken.at[idx, "LastContactDate"] = _us_date_from_iso(str(orig))
            log.append(
                InjectionLogRow(
                    row=_excel_row(idx),
                    column="LastContactDate",
                    class_name=CLASS_LABELS["mixed_us_iso_dates"],
                    original_value=_fmt_cell(orig),
                    corrupted_value=broken.at[idx, "LastContactDate"],
                )
            )

    # --- Exact duplicate MatterID ---
    dup_targets = _pick_indices(rng, 3, used)
    used.update(dup_targets)
    dup_sources = _pick_indices(rng, 3, used | set(dup_targets))
    if _injecting(only_class, "exact_duplicate_matter_id"):
        for tgt, src in zip(dup_targets, dup_sources, strict=True):
            orig = broken.at[tgt, "MatterID"]
            new_id = broken.at[src, "MatterID"]
            broken.at[tgt, "MatterID"] = new_id
            log.append(
                InjectionLogRow(
                    row=_excel_row(tgt),
                    column="MatterID",
                    class_name=CLASS_LABELS["exact_duplicate_matter_id"],
                    original_value=_fmt_cell(orig),
                    corrupted_value=new_id,
                )
            )

    # --- Status case / punctuation variants ---
    st_rows = _pick_indices(rng, 4, used)
    used.update(st_rows)

    def _status_variant(orig: str, kind: int) -> str:
        if kind == 0:
            return orig.lower()
        if kind == 1:
            return orig.upper()
        if kind == 2:
            return "On-Hold" if orig == "On Hold" else f"{orig}-"
        return f"{orig} "

    if _injecting(only_class, "status_case_punctuation_variants"):
        for n, idx in enumerate(st_rows):
            orig = broken.at[idx, "Status"]
            broken.at[idx, "Status"] = _status_variant(str(orig), n)
            log.append(
                InjectionLogRow(
                    row=_excel_row(idx),
                    column="Status",
                    class_name=CLASS_LABELS["status_case_punctuation_variants"],
                    original_value=_fmt_cell(orig),
                    corrupted_value=broken.at[idx, "Status"],
                )
            )

    # --- Currency / bracket text (openpyxl text cells) ---
    cur_rows = _pick_indices(rng, 3, used)
    used.update(cur_rows)
    currency_targets: list[tuple[int, str]] = []
    templates = ["${:,.2f}", "({:,.2f})", "${:,.2f}"]
    if _injecting(only_class, "currency_and_bracket_text"):
        for idx, tmpl in zip(cur_rows, templates, strict=True):
            orig = broken.at[idx, "FeeBilled"]
            if "(" in tmpl:
                text_val = tmpl.format(orig)
            else:
                text_val = tmpl.format(float(orig))
            currency_targets.append((idx, text_val))
            log.append(
                InjectionLogRow(
                    row=_excel_row(idx),
                    column="FeeBilled",
                    class_name=CLASS_LABELS["currency_and_bracket_text"],
                    original_value=_fmt_cell(orig),
                    corrupted_value=text_val,
                )
            )

    # --- Invisible characters (openpyxl) ---
    inv_rows = _pick_indices(rng, 3, used)
    used.update(inv_rows)
    invisible_targets: list[tuple[int, str, str]] = []
    if _injecting(only_class, "invisible_characters"):
        for j, idx in enumerate(inv_rows):
            col = "FeeBilled" if j < 2 else "PolicyAmount"
            orig = broken.at[idx, col]
            corrupted = f"\u00a0{_fmt_cell(orig)}" if j == 2 else f"'{_fmt_cell(orig)}"
            invisible_targets.append((idx, col, corrupted))
            log.append(
                InjectionLogRow(
                    row=_excel_row(idx),
                    column=col,
                    class_name=CLASS_LABELS["invisible_characters"],
                    original_value=_fmt_cell(orig),
                    corrupted_value=corrupted,
                )
            )

    # --- TOTAL row inside range ---
    total_idx = _pick_indices(rng, 1, used)[0]
    used.add(total_idx)
    if _injecting(only_class, "total_row_in_data_range"):
        orig_mid = broken.at[total_idx, "MatterID"]
        broken.at[total_idx, "MatterID"] = "TOTAL"
        broken.at[total_idx, "ClientName"] = "TOTAL"
        total_fee = round(float(broken.at[total_idx, "FeeBilled"]) + 12_500.0, 2)
        broken.at[total_idx, "FeeBilled"] = total_fee
        log.append(
            InjectionLogRow(
                row=_excel_row(total_idx),
                column="MatterID",
                class_name=CLASS_LABELS["total_row_in_data_range"],
                original_value=_fmt_cell(orig_mid),
                corrupted_value="TOTAL",
            )
        )

    # Merged cell row anchors (avoid overlap with reserved rows where possible)
    merge_a_start = _pick_indices(rng, 1, used)[0]
    used.add(merge_a_start)
    if merge_a_start >= CONFIG["BASE_DATA_ROWS"] - 3:
        merge_a_start = 400
    merge_b_start = _pick_indices(rng, 1, used)[0]
    used.add(merge_b_start)
    if merge_b_start >= CONFIG["BASE_DATA_ROWS"] - 2 or merge_b_start in range(
        merge_a_start, merge_a_start + 3
    ):
        merge_b_start = 800
    merge_specs = [
        (merge_a_start, 3, "ClientName"),
        (merge_b_start, 2, "Owner"),
    ]

    # Hidden block (5 contiguous rows)
    hidden_start = _pick_indices(rng, 1, used)[0]
    used.add(hidden_start)
    if hidden_start > CONFIG["BASE_DATA_ROWS"] - CONFIG["hidden_row_block_size"]:
        hidden_start = 600
    hidden_rows = list(
        range(hidden_start, hidden_start + CONFIG["hidden_row_block_size"])
    )

    # --- Spelling-variant duplicate rows (adds 4 rows) ---
    variant_sources = _pick_indices(rng, 4, set())
    spelling_variants = [
        (" Holdings LLC", ", L.L.C."),
        (" Inc", " Incorporated"),
        (" Partners LLP", " Partners, LLP"),
        (" Corp", " Corporation"),
    ]
    if _injecting(only_class, "duplicate_client_spelling_variant"):
        new_rows: list[dict[str, Any]] = []
        for src_idx, (suffix_find, suffix_rep) in zip(
            variant_sources, spelling_variants, strict=True
        ):
            row = broken.iloc[src_idx].to_dict()
            name = str(row["ClientName"])
            if suffix_find.strip() in name:
                variant_name = name.replace(suffix_find.strip(), suffix_rep.strip(","))
            else:
                variant_name = name + suffix_rep.strip(",")
            row["ClientName"] = variant_name
            row["MatterID"] = f"M-2026-V{len(new_rows) + 1:02d}"
            new_rows.append(row)
        variant_df = pd.DataFrame(new_rows, columns=COLUMNS)
        base_len = len(broken)
        broken = pd.concat([broken, variant_df], ignore_index=True)
        for i, src_idx in enumerate(variant_sources):
            excel_row = _excel_row(base_len + i)
            log.append(
                InjectionLogRow(
                    row=excel_row,
                    column="ClientName",
                    class_name=CLASS_LABELS["duplicate_client_spelling_variant"],
                    original_value=_fmt_cell(clean.at[src_idx, "ClientName"]),
                    corrupted_value=broken.at[base_len + i, "ClientName"],
                )
            )

      # --- Rows appended below naive SUM range (3 rows) ---
    append_start = len(broken)
    if _injecting(only_class, "rows_below_total_range"):
        append_rows: list[dict[str, Any]] = []
        for j in range(CONFIG["rows_below_total_range"]):
            open_d = _rand_open_date(rng)
            fee = round(rng.uniform(1500.0, 4200.0), 2)
            append_rows.append(
                {
                    "MatterID": f"M-2026-X{j + 1:02d}",
                    "ClientName": f"Late Entry Client {j + 1}",
                    "ClientType": "Entity",
                    "MatterType": "Closing",
                    "OpenDate": _date_to_iso(open_d),
                    "TargetCloseDate": _date_to_iso(open_d + timedelta(days=45)),
                    "Status": "Open",
                    "Owner": rng.choice(OWNERS),
                    "PolicyAmount": round(rng.uniform(100_000.0, 800_000.0), 2),
                    "FeeBilled": fee,
                    "FeeCollected": 0.0,
                    "InvoiceCount": 1,
                    "LastContactDate": _date_to_iso(open_d),
                    "Notes": "Appended below prior total range",
                }
            )
        append_df = pd.DataFrame(append_rows, columns=COLUMNS)
        broken = pd.concat([broken, append_df], ignore_index=True)
        for j in range(CONFIG["rows_below_total_range"]):
            excel_row = _excel_row(append_start + j)
            log.append(
                InjectionLogRow(
                    row=excel_row,
                    column="FeeBilled",
                    class_name=CLASS_LABELS["rows_below_total_range"],
                    original_value="",
                    corrupted_value=_fmt_cell(broken.at[append_start + j, "FeeBilled"]),
                )
            )
    else:
        for _j in range(CONFIG["rows_below_total_range"]):
            _rand_open_date(rng)
            rng.uniform(1500.0, 4200.0)
            rng.uniform(100_000.0, 800_000.0)
            rng.choice(OWNERS)

    postprocess = {
        "text_targets": text_targets if _injecting(only_class, "numbers_stored_as_text") else [],
        "currency_targets": currency_targets
        if _injecting(only_class, "currency_and_bracket_text")
        else [],
        "invisible_targets": invisible_targets
        if _injecting(only_class, "invisible_characters")
        else [],
        "merge_specs": merge_specs if _injecting(only_class, "merged_cells") else [],
        "hidden_rows": hidden_rows if _injecting(only_class, "hidden_rows") else [],
    }
    return broken, log, postprocess


def write_tracker_xlsx(df: pd.DataFrame, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_excel(path, index=False, sheet_name=SHEET_NAME)


def append_structure_defect_logs(
    log: list[InjectionLogRow],
    postprocess: dict[str, Any],
    broken: pd.DataFrame,
) -> None:
    for start_idx, span, col in postprocess["merge_specs"]:
        top_val = broken.at[start_idx, col]
        start_row = _excel_row(start_idx)
        end_row = start_row + span - 1
        col_letter = _col_letter(col)
        log.append(
            InjectionLogRow(
                row=start_row,
                column=col,
                class_name=CLASS_LABELS["merged_cells"],
                original_value=_fmt_cell(top_val),
                corrupted_value=(
                    f"merged {span} rows "
                    f"({col_letter}{start_row}:{col_letter}{end_row})"
                ),
            )
        )

    hidden = postprocess["hidden_rows"]
    log.append(
        InjectionLogRow(
            row=_excel_row(hidden[0]),
            column="(rows)",
            class_name=CLASS_LABELS["hidden_rows"],
            original_value="visible",
            corrupted_value=(
                f"hidden rows {_excel_row(hidden[0])}-"
                f"{_excel_row(hidden[-1])} ({CONFIG['hidden_row_block_size']} rows)"
            ),
        )
    )


def apply_openpyxl_postprocess(path: Path, postprocess: dict[str, Any]) -> None:
    wb = load_workbook(path)
    ws = wb[SHEET_NAME]

    for idx, col, _key in postprocess["text_targets"]:
        excel_row = _excel_row(idx)
        cell = ws[f"{_col_letter(col)}{excel_row}"]
        cell.value = _fmt_cell(cell.value)
        cell.number_format = "@"

    for idx, text_val in postprocess["currency_targets"]:
        excel_row = _excel_row(idx)
        cell = ws[f"J{excel_row}"]
        cell.value = text_val
        cell.number_format = "@"

    for idx, col, corrupted in postprocess["invisible_targets"]:
        excel_row = _excel_row(idx)
        cell = ws[f"{_col_letter(col)}{excel_row}"]
        cell.value = corrupted
        cell.number_format = "@"

    for start_idx, span, col in postprocess["merge_specs"]:
        col_letter = _col_letter(col)
        start_row = _excel_row(start_idx)
        end_row = start_row + span - 1
        ws.merge_cells(f"{col_letter}{start_row}:{col_letter}{end_row}")
        ws[f"{col_letter}{start_row}"].alignment = Alignment(
            vertical="center", horizontal="left"
        )

    hidden = postprocess["hidden_rows"]
    for ridx in hidden:
        ws.row_dimensions[_excel_row(ridx)].hidden = True

    wb.save(path)


