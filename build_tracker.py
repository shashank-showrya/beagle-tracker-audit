def _fmt_cell(value: Any) -> str:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return ""
    if isinstance(value, date):
        return value.isoformat()
    return str(value)


def _excel_row(df_index: int) -> int:
    """DataFrame 0-based index -> Excel 1-based row (header on row 1)."""
    return df_index + 2


def _date_to_iso(d: date) -> str:
    return d.isoformat()


def _rand_open_date(rng: random.Random) -> date:
    span = (OPEN_DATE_END - OPEN_DATE_START).days
    return OPEN_DATE_START + timedelta(days=rng.randint(0, span))


def _client_name(rng: random.Random, entity: bool) -> str:
    first = rng.choice(FIRST_NAMES)
    last = rng.choice(LAST_NAMES)
    if entity:
        return f"{first} {last}"
    return f"{first} {rng.choice(['A.', 'B.', 'C.', 'D.'])} {last.split()[0]}"


def generate_base_rows(rng: random.Random) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for i in range(CONFIG["BASE_DATA_ROWS"]):
        entity = rng.random() < 0.55
        open_d = _rand_open_date(rng)
        target = open_d + timedelta(days=rng.randint(14, 120))
        last_contact = open_d + timedelta(days=rng.randint(0, 90))
        fee_billed = round(rng.uniform(250.0, 8500.0), 2)
        fee_collected = round(fee_billed * rng.uniform(0.0, 1.0), 2)
        policy = round(rng.uniform(50_000.0, 2_500_000.0), 2)
        rows.append(
            {
                "MatterID": f"M-2026-{i + 1:05d}",
                "ClientName": _client_name(rng, entity),
                "ClientType": "Entity" if entity else "Individual",
                "MatterType": rng.choice(MATTER_TYPES),
                "OpenDate": _date_to_iso(open_d),
                "TargetCloseDate": _date_to_iso(target),
                "Status": rng.choice(STATUSES),
                "Owner": rng.choice(OWNERS),
                "PolicyAmount": policy,
                "FeeBilled": fee_billed,
                "FeeCollected": fee_collected,
                "InvoiceCount": rng.randint(1, 4),
                "LastContactDate": _date_to_iso(last_contact),
                "Notes": "" if rng.random() < 0.85 else "Follow up scheduled",
            }
        )
    return pd.DataFrame(rows, columns=COLUMNS)


def _pick_indices(rng: random.Random, n: int, exclude: set[int]) -> list[int]:
    pool = [i for i in range(CONFIG["BASE_DATA_ROWS"]) if i not in exclude]
    rng.shuffle(pool)
    if len(pool) < n:
        raise RuntimeError(f"Not enough rows to pick {n} indices")
    return pool[:n]


def _us_date_from_iso(iso: str) -> str:
    y, m, d = iso.split("-")
    return f"{int(m):02d}/{int(d):02d}/{y}"


def _injecting(only_class: str | None, class_key: str) -> bool:
    """When only_class is set, apply/log just that CONFIG key (RNG path unchanged)."""
    return only_class is None or only_class == class_key


