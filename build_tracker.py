def verify_gap_reconciliation(
    gap_rows: list[GapResult], full_gap: float, rtol: float = 1e-9
) -> list[str]:
    issues: list[str] = []
    class_rows = [r for r in gap_rows if r.error_class != INTERACTION_LABEL]
    interaction = next(r for r in gap_rows if r.error_class == INTERACTION_LABEL)
    if len(class_rows) != 12:
        issues.append(f"expected 12 class rows, got {len(class_rows)}")
    s = sum(r.gap for r in class_rows) + interaction.gap
    if abs(s - full_gap) > max(abs(full_gap) * rtol, 0.01):
        issues.append(
            f"reconciliation: sum(class gaps)+interaction={s} != full_gap={full_gap}"
        )
    return issues


def run_integrity_checks(
    clean: pd.DataFrame,
    broken: pd.DataFrame,
    log: list[InjectionLogRow],
    log_path: Path,
) -> list[str]:
    issues: list[str] = []

    if len(clean) != CONFIG["BASE_DATA_ROWS"]:
        issues.append(f"clean row count {len(clean)} != {CONFIG['BASE_DATA_ROWS']}")
    expected_broken = (
        CONFIG["BASE_DATA_ROWS"]
        + CONFIG["duplicate_client_spelling_variant"]
        + CONFIG["rows_below_total_range"]
    )
    if len(broken) != expected_broken:
        issues.append(f"broken row count {len(broken)} != {expected_broken}")

    if len(log) != injection_total():
        issues.append(f"log rows {len(log)} != {injection_total()}")

    counts: dict[str, int] = {}
    for entry in log:
        counts[entry.class_name] = counts.get(entry.class_name, 0) + 1
    for label, expected in SPEC_CLASS_COUNTS.items():
        if counts.get(label, 0) != expected:
            issues.append(
                f"class {label!r}: log has {counts.get(label, 0)}, spec expects {expected}"
            )

    for col in clean.columns:
        if FORBIDDEN_FIELD_PATTERN.search(col):
            issues.append(f"forbidden column name {col!r}")

    fc = clean["FeeCollected"].astype(float)
    fb = clean["FeeBilled"].astype(float)
    if (fc > fb).any():
        issues.append("clean file has FeeCollected > FeeBilled")

    open_parsed = pd.to_datetime(clean["OpenDate"], format="%Y-%m-%d", errors="coerce")
    if open_parsed.isna().any():
        issues.append("clean OpenDate has non-ISO values")
    if open_parsed.min().date() < OPEN_DATE_START:
        issues.append("OpenDate before spec range")
    if open_parsed.max().date() > OPEN_DATE_END:
        issues.append("OpenDate after spec range")

    digest = hashlib.sha256(log_path.read_bytes()).hexdigest()
    issues.extend(_reproducibility_check(digest))

    return issues


def _log_csv_bytes(log: list[InjectionLogRow]) -> bytes:
    import io

    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=LOG_FIELDS)
    writer.writeheader()
    for entry in log:
        writer.writerow(entry.as_dict())
    return buf.getvalue().encode("utf-8")


def _reproducibility_check(expected_hex: str) -> list[str]:
    """Re-generate injection log (including merge/hidden entries) and compare."""
    issues: list[str] = []
    rng = random.Random(CONFIG["SEED"])
    clean = generate_base_rows(rng)
    broken, log, postprocess = apply_injections(clean, rng)
    log_copy = deepcopy(log)
    append_structure_defect_logs(log_copy, postprocess, broken)
    second = hashlib.sha256(_log_csv_bytes(log_copy)).hexdigest()
    if second != expected_hex:
        issues.append("injection log not reproducible vs in-memory regeneration")
    return issues


def build_seed1() -> tuple[pd.DataFrame, pd.DataFrame, list[InjectionLogRow]]:
    rng = random.Random(CONFIG["SEED"])
    random.seed(CONFIG["SEED"])
    clean = generate_base_rows(rng)
